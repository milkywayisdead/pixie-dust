function parse(frameId: string, frameStr: string): FrameObject {
    const shape = frameStr.split('[')[0].split(',');
    const colorList = frameStr.split('[')[1].replace(']', '').split('|');
    const colorMap: ColorMap = {};
    for(const cl of colorList){
        if(cl === '') continue;

        const _ = cl.split(':');
        const color = _[0];
        const cells = JSON.parse(`[${_[1]}]`);
        colorMap[color] = cells;
    }

    return {
        id: frameId,
        colorMap: colorMap,
        rows: Number(shape[0]),
        cols: Number(shape[1]),
    } as FrameObject;
}

